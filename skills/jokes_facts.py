class JokesAndFactsSkill(BaseSkill):
    """Фирменный навык развлечений Алисы: анекдоты, факты, тосты, сказки, комплименты."""

    FOLLOWUP_EXACT = {
        "еще", "ещё", "давай еще", "давай ещё", "еще один", "ещё один",
        "еще одну", "ещё одну", "другой", "другую", "следующий", "следующую",
        "посмешнее", "повтори", "еще факт", "ещё факт", "еще шутку", "ещё шутку",
        "еще анекдот", "ещё анекдот", "расскажи еще", "расскажи ещё",
        "давай другой", "давай другую", "дальше", "другую шутку", "другой факт"
    }

    def __init__(self):
        self._last_kind = "joke"

    def can_handle(self, context: RequestContext) -> bool:
        text = context.raw_text.lower().strip()
        triggers = [
            "анекдот", "анекдоты", "шутку", "шутка", "пошути", "рассмеши", "юмор",
            "интересный факт", "расскажи факт", "что-нибудь интересное", "удиви меня",
            "случайный факт", "тост", "скажи тост", "подними тост",
            "цитата", "цитату", "мудрая мысль", "сказку", "сказка", "расскажи историю",
            "комплимент", "похвали меня", "скажи приятное"
        ]
        return any(trig in text for trig in triggers)

    def accepts_followup(self, context: RequestContext) -> bool:
        text = context.raw_text.lower().strip()
        words = text.split()
        if not words or len(words) > 4:
            return False
        # Если фраза содержит предметный вопрос или обсуждение — отдаём в LLM (Groq)
        if any(w in text for w in ["про ", "почему", "зачем", "как ", "подробн", "думаешь", "знаешь", "скажешь"]):
            return False
        if text in self.FOLLOWUP_EXACT:
            return True
        return any(
            phrase in text
            for phrase in [
                "давай еще", "еще один", "еще факт", "еще шутк",
                "следующ", "расскажи еще", "посмешнее"
            ]
        )

    def execute(self, context: RequestContext) -> None:
        text = context.raw_text.lower().strip()

        if any(w in text for w in ["анекдот", "шутк", "пошути", "рассмеши", "юмор"]):
            kind = "joke"
        elif any(w in text for w in ["факт", "интересн", "удиви"]):
            kind = "fact"
        elif "тост" in text:
            kind = "toast"
        elif any(w in text for w in ["цитат", "мудрост", "мудрая"]):
            kind = "quote"
        elif any(w in text for w in ["сказк", "истори"]):
            kind = "tale"
        elif any(w in text for w in ["комплимент", "похвали", "приятное"]):
            kind = "compliment"
        elif text in self.FOLLOWUP_EXACT or any(w in text for w in ["еще", "ещё", "другой", "другую", "следующ"]):
            kind = self._last_kind
        else:
            kind = "joke"

        self._last_kind = kind
        if kind == "fact":
            context.speak(random.choice(FACTS))
        elif kind == "toast":
            context.speak(random.choice(TOASTS))
        elif kind == "quote":
            context.speak(random.choice(QUOTES))
        elif kind == "tale":
            context.speak(random.choice(FAIRYTALES))
        elif kind == "compliment":
            context.speak(random.choice(COMPLIMENTS))
        else:
            context.speak(random.choice(JOKES))
